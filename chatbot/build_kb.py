#!/usr/bin/env python3
"""Build chatbot/knowledge-base.md for the ElevenLabs website assistant (2026-11-18, Rohit).

  python3 chatbot/build_kb.py

Reads the main-site and careers pages (only the <main> text) plus the Academy course
content in academy-wp/content/, and writes one Markdown file to upload to the agent's
Knowledge Base in the ElevenLabs dashboard. Re-run and re-upload whenever pages change.
Standard library only.
"""
from html.parser import HTMLParser
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SKIP = {"script", "style", "svg", "figure"}


class Text(HTMLParser):
    def __init__(self, whole=False):
        super().__init__(convert_charrefs=True)
        self.out, self.skip, self.on = [], 0, whole

    def handle_starttag(self, t, a):
        if t == "main":
            self.on = True
        if t in SKIP:
            self.skip += 1
        if t in ("h1", "h2", "h3", "h4"):
            self.out.append("\n" + "#" * (int(t[1]) + 2) + " ")
        if t in ("p", "li", "div", "br", "tr"):
            self.out.append("\n")

    def handle_endtag(self, t):
        if t in SKIP:
            self.skip -= 1
        if t == "main":
            self.on = False

    def handle_data(self, d):
        if self.on and not self.skip and d.strip():
            self.out.append(" ".join(d.split()) + " ")


def text(path, whole=False):
    p = Text(whole)
    p.feed(path.read_text(encoding="utf-8"))
    return "\n".join(l.strip() for l in "".join(p.out).split("\n") if l.strip())


FACTS = """## Key facts (always true; prefer these over anything else)

- Company: Coral Petal AI, an Agentic AI consultancy for enterprises and governments, based in India. Coral Petal AI™ and the Petal Network logo are trademarks (applications filed in India).
- Services: Strategy & readiness, Agent implementation, Run & govern (evaluation, monitoring, guardrails), Team enablement (training through the Academy).
- Clouds: Microsoft Azure, AWS and Google Cloud.
- Academy (academy.coralpetal.ai): The Coral Petal Signature Course, end-to-end Generative and Agentic AI, 8 modules, about 50 hours, USD 100 with 20% off = USD 80. Fundamentals courses: about 20 hours each, USD 50, now USD 20. Every enrolment gives 1 year of access. Live sessions and bootcamps are planned.
- Careers (careers.coralpetal.ai): open role Video Editor; apply on the careers site.
- Contact: contact@coralpetal.ai (services and partnerships), academy@coralpetal.ai (courses and corporate training), careers@coralpetal.ai (jobs). The contact form at coralpetal.ai/contact/ reaches the right team; replies within two working days.
- Socials: LinkedIn /company/coralpetalai, Instagram and X @CoralPetalAI.
"""


def main():
    parts = ["# Coral Petal AI — website assistant knowledge base\n",
             "Generated by chatbot/build_kb.py from the website and Academy content.\n", FACTS]
    pages = [("Home", "site/index.html"), ("About: what we do", "site/about/index.html"),
             ("Core vision", "site/vision/index.html"), ("Services", "site/services/index.html"),
             ("Industries", "site/industries/index.html"), ("Insights", "site/insights/index.html"),
             ("Contact", "site/contact/index.html"), ("Careers", "careers/index.html"),
             ("Open roles", "careers/openings/index.html"), ("Video Editor role", "careers/video-editor/index.html")]
    for name, f in pages:
        parts.append(f"\n## Page: {name}\n\n{text(ROOT / f)}\n")
    a = ROOT / "academy-wp" / "content"
    parts.append("\n## Academy: The Coral Petal Signature Course\n\n" + text(a / "course.html", True) + "\n")
    mods = [l.split("\t") for l in (a / "modules.tsv").read_text(encoding="utf-8").splitlines() if l.strip()]
    parts.append("\n### Modules\n\n" + "\n".join(f"- {m[1]}: {m[2]}" for m in mods if len(m) > 2) + "\n")
    parts.append("\n## Academy: Live sessions\n\n" + text(a / "live-sessions.html", True) + "\n")
    for c in sorted((a / "catalog").glob("*.html")):
        title = c.stem.replace("-", " ").title().replace("Az ", "AZ-").replace("Ai ", "AI ")
        parts.append(f"\n## Academy course: {title}\n\n" + text(c, True) + "\n")
    out = Path(__file__).with_name("knowledge-base.md")
    out.write_text("\n".join(parts), encoding="utf-8")
    print(f"wrote {out.relative_to(ROOT)} ({len(out.read_text().split())} words)")


if __name__ == "__main__":
    main()
